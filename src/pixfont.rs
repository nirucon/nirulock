fn table() -> &'static [[u8; 8]; 96] {
    static T: OnceLock<[[u8; 8]; 96]> = OnceLock::new();
    T.get_or_init(|| {
        let mut t = [[0xffu8; 8]; 96];
        for (c, s) in GLYPHS {
            if s.len() != 64 {
                continue;
            }
            let i = *c as usize - 0x20;
            for (row, chunk) in s.as_bytes().chunks(8).enumerate() {
                let mut bits = 0u8;
                for (col, b) in chunk.iter().enumerate() {
                    if *b == b'#' {
                        bits |= 0x80 >> col;
                    }
                }
                t[i][row] = bits;
            }
        }
        t
    })
}

/// The rows of a character (bit 7 is the left column).
pub fn glyph(c: char) -> [u8; 8] {
    let c = c.to_ascii_uppercase();
    let i = c as u32;
    if (0x20..0x80).contains(&i) {
        let g = table()[(i - 0x20) as usize];
        if g != [0xff; 8] {
            return g;
        }
    }
    // A block for anything else, like the C64's reverse space.
    [0, 0x7e, 0x7e, 0x7e, 0x7e, 0x7e, 0x7e, 0]
}

/// Text the font can show: Swedish and other Latin letters lose their
/// marks (Å and Ä become A, Ö becomes O, é becomes E), typographic quotes
/// and dashes become their plain ASCII forms, and whatever is left that the
/// font does not have is dropped, so a quote never shows a row of blocks.
pub fn plain(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for c in text.chars() {
        if c.is_ascii() && !c.is_ascii_control() {
            out.push(c);
            continue;
        }
        let lower = c.to_lowercase().next().unwrap_or(c);
        let letter: Option<&str> = match lower {
            'å' | 'ä' | 'à' | 'á' | 'â' | 'ã' => Some("a"),
            'æ' => Some("ae"),
            'ö' | 'ø' | 'ò' | 'ó' | 'ô' | 'õ' => Some("o"),
            'é' | 'è' | 'ê' | 'ë' => Some("e"),
            'í' | 'ì' | 'î' | 'ï' => Some("i"),
            'ú' | 'ù' | 'û' | 'ü' => Some("u"),
            'ý' | 'ÿ' => Some("y"),
            'ç' => Some("c"),
            'ñ' => Some("n"),
            'ß' => Some("ss"),
            'þ' => Some("th"),
            'ð' => Some("d"),
            _ => None,
        };
        if let Some(letter) = letter {
            if c.is_uppercase() {
                out.push_str(&letter.to_uppercase());
            } else {
                out.push_str(letter);
            }
            continue;
        }
        out.push_str(match c {
            '\u{2018}' | '\u{2019}' | '\u{b4}' => "'",
            '\u{201c}' | '\u{201d}' | '\u{ab}' | '\u{bb}' | '\u{201e}' => "\"",
            '\u{2013}' | '\u{2014}' | '\u{2212}' => "-",
            '\u{2026}' => "...",
            '\u{b7}' | '\u{2022}' => "*",
            '\t' | '\n' | '\r' | '\u{a0}' => " ",
            _ => "",
        });
    }
    out.chars().filter(|c| covered(*c)).collect()
}

fn covered(c: char) -> bool {
    let i = c.to_ascii_uppercase() as u32;
    (0x20..0x80).contains(&i) && table()[(i - 0x20) as usize] != [0xff; 8]
}

/// The lit cells of `text` as runs: (column, row, length) in font pixels,
/// columns counted from the first character's left edge.
pub fn runs(text: &str) -> Vec<(i32, i32, i32)> {
    let mut out = Vec::new();
    for (index, c) in text.chars().enumerate() {
        let g = glyph(c);
        let x0 = index as i32 * 8;
        for (row, bits) in g.iter().enumerate() {
            let mut col = 0;
            while col < 8 {
                if bits & (0x80 >> col) != 0 {
                    let start = col;
                    while col < 8 && bits & (0x80 >> col) != 0 {
                        col += 1;
                    }
                    out.push((x0 + start, row as i32, col - start));
                } else {
                    col += 1;
                }
            }
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_glyph_is_8x8_and_the_logo_letters_exist() {
        for (c, s) in GLYPHS {
            assert_eq!(s.len(), 64, "glyph {c:?}");
        }
        for c in "NIRUX LOCKED 0123456789:-.*!?".chars() {
            assert!(covered(c), "{c:?}");
        }
        assert_eq!(glyph('a'), glyph('A'));
        assert_eq!(glyph(' '), [0; 8]);
        assert_eq!(glyph('A')[3], 0b0111_1110);
    }

    #[test]
    fn plain_text_keeps_swedish_quotes_readable() {
        assert_eq!(plain("Bättre börda bär du ej"), "Battre borda bar du ej");
        assert_eq!(plain("“Åter” \u{2014} Hávamál…"), "\"Ater\" - Havamal...");
        assert_eq!(plain("♪ tune\tname"), " tune name");
        assert_eq!(plain("漢字 ok"), " ok");
    }

    #[test]
    fn runs_cover_every_lit_pixel_once() {
        let lit: i32 = "NIRUX"
            .chars()
            .map(|c| glyph(c).iter().map(|b| b.count_ones() as i32).sum::<i32>())
            .sum();
        let runs = runs("NIRUX");
        assert_eq!(runs.iter().map(|r| r.2).sum::<i32>(), lit);
        assert!(runs
            .iter()
            .all(|(x, y, n)| *x >= 0 && *x + n <= 40 && (0..8).contains(y)));
    }
}
